"""Stable abstractions (core knows nothing about concrete plugins)."""
from typing import Any, Protocol

class Repository(Protocol):
    def execute(self, sql: str, args: tuple = ()) -> Any: ...
    def one(self, sql: str, args: tuple = ()) -> dict | None: ...
    def all(self, sql: str, args: tuple = ()) -> list[dict]: ...
    def transaction(self) -> Any: ...

class AccountsAPI(Protocol):
    def account(self, account_id: int) -> dict: ...
    def debit(self, account_id: int, cents: int) -> None: ...
    def credit(self, account_id: int, cents: int) -> None: ...

class FeesAPI(Protocol):
    def calculate(self, amount: int) -> int: ...

class CurrencyAPI(Protocol):
    def convert(self, amount: int, src: str, dst: str) -> int: ...

class AuthAPI(Protocol):
    def register(self, login: str, email: str, password: str) -> int: ...
    def login(self, login: str, password: str) -> dict: ...

class BonusAPI(Protocol):
    def points(self, owner_id: int) -> int: ...

class ReportsAPI(Protocol):
    def statement(self, account_id: int, since=None, until=None, kind=None) -> list[dict]: ...
